import { NextResponse } from 'next/server';
import fs from 'fs';
import path from 'path';
import { requireSession } from '@/lib/auth';
import { getUploadedFileById, listLabReports } from '@/lib/data-store';

const UPLOAD_ROOT = path.resolve(process.cwd(), '.mhms-uploads');

function buildMinimalPdfBuffer(title: string, subtitle: string, notes: string): Buffer {
  const safe = (s: string) => s.replace(/[()\\]/g, '').slice(0, 90);
  const content = `BT /F1 16 Tf 50 750 Td (${safe(title)}) Tj /F1 11 Tf 0 -24 Td (${safe(subtitle)}) Tj 0 -20 Td (${safe(notes)}) Tj ET`;
  const objects = [
    '1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj',
    '2 0 obj << /Type /Pages /Kids [3 0 R] /Count 1 >> endobj',
    '3 0 obj << /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >> endobj',
    `4 0 obj << /Length ${Buffer.byteLength(content)} >> stream\n${content}\nendstream endobj`,
    '5 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> endobj',
  ];
  let pdf = '%PDF-1.4\n';
  const offsets: number[] = [0];
  for (const obj of objects) {
    offsets.push(Buffer.byteLength(pdf));
    pdf += obj + '\n';
  }
  const xrefOffset = Buffer.byteLength(pdf);
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (let i = 1; i < offsets.length; i++) {
    pdf += String(offsets[i]).padStart(10, '0') + ' 00000 n \n';
  }
  pdf += `trailer << /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;
  return Buffer.from(pdf, 'utf-8');
}

export async function GET(
  _request: Request,
  { params }: { params: { id: string } }
) {
  const auth = await requireSession(['ADMIN', 'DOCTOR', 'PATIENT']);
  if (auth.error || !auth.session) {
    return NextResponse.json({ error: auth.error }, { status: auth.status });
  }

  const fileRecord = await getUploadedFileById(params.id);
  const allReports = await listLabReports();
  const linkedReport = allReports.find(
    (r) => r.uploadedFileId === params.id || r.fileUrl.includes(params.id)
  );

  if (!fileRecord && !linkedReport) {
    return NextResponse.json({ error: 'File not found.' }, { status: 404 });
  }

  const { role, id: userId } = auth.session.user;
  const ownerPatientId = fileRecord?.patientId || linkedReport?.patientId;
  const uploaderId = fileRecord?.uploadedById || linkedReport?.doctorId;

  const authorized =
    role === 'ADMIN' ||
    (role === 'DOCTOR' && (uploaderId === userId || ownerPatientId !== undefined)) ||
    (role === 'PATIENT' && ownerPatientId === userId);

  if (!authorized) {
    return NextResponse.json({ error: 'Forbidden' }, { status: 403 });
  }

  const fileName = fileRecord?.fileName || linkedReport?.fileName || 'mhms-lab-report.pdf';
  const fileType = fileRecord?.fileType || linkedReport?.fileType || 'application/pdf';

  // If external Vercel Blob URL, redirect safely after auth verification
  if (fileRecord?.fileUrl && fileRecord.fileUrl.startsWith('https://')) {
    return NextResponse.redirect(fileRecord.fileUrl);
  }

  // Check local disk storage with path confinement check
  if (fileRecord?.localPath) {
    const resolved = path.resolve(fileRecord.localPath);
    if (resolved.startsWith(UPLOAD_ROOT + path.sep) && fs.existsSync(resolved)) {
      const data = fs.readFileSync(resolved);
      return new NextResponse(data, {
        status: 200,
        headers: {
          'Content-Type': fileType,
          'Content-Disposition': `attachment; filename="${fileName.replace(/"/g, '')}"`,
          'X-Content-Type-Options': 'nosniff',
        },
      });
    }
  }

  // Generate clean clinical PDF document for seeded sample reports
  const pdfBuffer = buildMinimalPdfBuffer(
    linkedReport?.reportTitle || 'MHMS Diagnostic Lab Report',
    `Patient: ${linkedReport?.patient?.fullName || 'Patient Record'} | Date: ${linkedReport?.reportDate || '2026-10-10'}`,
    linkedReport?.notes || 'Clinical laboratory summary generated by MHMS.'
  );

  return new NextResponse(new Uint8Array(pdfBuffer), {
    status: 200,
    headers: {
      'Content-Type': 'application/pdf',
      'Content-Disposition': `attachment; filename="${fileName.replace(/"/g, '')}"`,
      'X-Content-Type-Options': 'nosniff',
    },
  });
}
